"""Generate docs/reports.md from the catalogue in src/pse_opendata/catalog.py.

A test checks that the committed page matches the catalogue, so run this after changing the catalogue.

Usage:
    python scripts/gen_docs.py            # write docs/reports.md
    python scripts/gen_docs.py --check    # exit 1 if docs/reports.md is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from pse_opendata.catalog import (
    CHECKED_ON,
    FIELD_MAP,
    LEGACY_REPORTS,
    OPENAPI,
    REPORTS,
    Field,
)

OUT = Path(__file__).resolve().parents[1] / "docs" / "reports.md"
GROUPS = {"prices": "Prices", "balancing": "Balancing market", "system": "Power system"}


def _unit(f: Field) -> str:
    if f.unit is None:
        return "text" if f.dtype == "str" else ""
    return f.unit if f.unit_verified else f"{f.unit} (unverified)"


def _fields(fields: tuple[Field, ...]) -> list[str]:
    lines = ["| Field | Description | Unit |", "|---|---|---|"]
    lines += [f"| `{f.name}` | {f.description} | {_unit(f)} |" for f in fields]
    return lines


def render() -> str:
    out = [
        "# Report catalogue",
        "",
        "<!-- generated by scripts/gen_docs.py from src/pse_opendata/catalog.py; do not edit by hand -->",
        "",
        f"Checked on {CHECKED_ON:%Y-%m-%d} against the [OpenAPI description]({OPENAPI}) of the reports API, the "
        f"[field map]({FIELD_MAP}), the report pages on raporty.pse.pl and the API itself. A unit that no PSE "
        "source confirms is marked *unverified*. Prices: PSE writes `zł/MWh` and `zł/MW-h`; here `PLN/MWh` "
        "(energy) and `PLN/MW/h` (capacity, per MW and hour).",
        "",
        "**Revision window**: how many days after the end of a month PSE republished data of that month "
        "(latest republication seen for September 2025 to October 2026, rounded up). The cache downloads a month "
        "again until it was fetched at least this long after the month ended.",
        "",
        "## Reports API",
        "",
        "| Report | Title | Resolution | From | Revision window |",
        "|---|---|---|---|---|",
    ]
    for r in REPORTS.values():
        out.append(f"| [`{r.name}`](#{r.name}) | {r.title} | {r.resolution} | {r.first_date} | "
                   f"{r.revision_days} days |")
    for group, heading in GROUPS.items():
        out += ["", f"### {heading}"]
        for r in (r for r in REPORTS.values() if r.group == group):
            out += [
                "",
                f"#### {r.name}",
                "",
                f"**{r.title}** ({r.title_pl}). {r.description}",
                "",
                f"- Resolution: {r.resolution}; rows stamped with the interval end (`{r.time_field}`)",
                f"- Available from business date {r.first_date}",
                f"- Revision window: {r.revision_days} days",
            ]
            if r.key:
                unique = "" if r.unique_key else "; rows can repeat exactly"
                out.append(f"- Several rows per interval, keyed by {', '.join(f'`{k}`' for k in r.key)}{unique}")
            out += [f"- PSE page: <{r.url}>", ""]
            out += _fields(r.fields)
            if r.notes:
                out += [""] + [f"- {note}" for note in r.notes]
    out += [
        "",
        "## Legacy export (until 2024-06-13)",
        "",
        "Hourly reports of the old www.pse.pl data service, available through "
        "`https://www.pse.pl/getcsv/-/export/csv/<CODE>/data_od/<YYYYMMDD>/data_do/<YYYYMMDD>`. The export does "
        "not state units; units below are inferred and marked unverified.",
    ]
    for r in LEGACY_REPORTS.values():
        out += [
            "",
            f"### {r.code}",
            "",
            f"**{r.title}** ({r.title_pl}). {r.description}",
            "",
            f"- Resolution: {r.resolution}, local hours 1-24 (hour 1 = 00:00-01:00)",
            f"- Available from {r.first_date} to {r.last_date}",
            f"- PSE archive page: <{r.page}>",
            "",
        ]
        out += _fields(r.fields)
        if r.notes:
            out += [""] + [f"- {note}" for note in r.notes]
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/reports.md is out of date; run python scripts/gen_docs.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
